def getEigVect(A, eigval):
    l1 = eigval
    a = [
        -A[0][1]/(A[0][0]-l1),#b
        -A[0][2]/(A[0][0]-l1),#c
        -A[0][3]/(A[0][0]-l1)#d
    ]

    b = [
        -(A[1][2] + A[1][0]*a[1])/((A[1][1]-l1) + A[1][0]*a[0]),
        -(A[1][3] + A[1][0]*a[2])/((A[1][1]-l1) + A[1][0]*a[0])
    ]

    c = [
        -((A[2][3] + A[2][0]*a[2]) + (A[2][1] + A[2][0]*a[0])*b[1]) / 
        (((A[2][2]-l1) + A[2][0]*a[1]) + (A[2][1] + A[2][0]*a[0])*b[0]),
    ]

    d = 1
    c = c[0]
    b = b[0]*c + b[1]*d
    a = a[0]*b + a[1]*c + a[2]*d

    return [a,b,c,d]